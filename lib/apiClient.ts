// Server Pokémon → frontend Monster
// Hunger, PP and status aren't tracked by the bot yet; these fields hold placeholder values
function spriteUrlFor(pokedexId: number | null): string {
  if (!pokedexId) {
    // No PokeAPI data came back (offline/rate-limited) — a neutral pokeball
    // icon reads better than a broken image, and doesn't imply real data.
    return 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/items/poke-ball.png';
  }
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/showdown/${pokedexId}.gif`;
}

export function mapServerPokemon(sp: ServerPokemon): Monster {
  const moves: MoveInstance[] = sp.moves.map((m) => ({
    id: m.id,
    name: m.name,
    type: m.type,
    power: m.power,
    accuracy: (m.accuracy ?? 100) / 100, // backend sends 0-100, frontend math expects 0-1
    pp: m.pp,
    maxPp: m.max_pp,
  }));

  return {
    uid: sp.id,
    speciesId: sp.species_name,
    name: sp.nickname?.toUpperCase() || sp.species_name.toUpperCase(),
    types: sp.types,
    level: sp.level,
    xp: sp.experience,
    xpToNext: sp.xp_to_next,
    hp: sp.current_hp,
    maxHp: sp.max_hp,
    attack: 0, // not surfaced by the API today — battle math runs server-side
    defense: 0,
    status: (['psn', 'brn', 'slp', 'par', 'frz'].includes(sp.status ?? '') ? sp.status : sp.status === 'tox' ? 'psn' : 'none') as MonsterStatus,
    hunger: 10,
    maxHunger: 10, // the bot has no hunger system — server monsters always read "full"
    portraitUrl: spriteUrlFor(sp.pokedex_id),
    moves,
    catchRate: 0, // unused for server monsters — /api/battle/catch decides server-side
    ability: sp.ability ?? undefined,
    abilityDesc: sp.ability_desc ?? undefined,
    isBoss: sp.is_boss ?? false,
    condition: sp.condition,
    encounterToken: sp.token,
    evolutions: sp.evolutions,
  };
}

let logIdCounter = 0;
export function serverLogToEntries(lines: string[]): LogEntry[] {
  return lines.map((text) => {
    logIdCounter += 1;
    return { id: `srv-${Date.now()}-${logIdCounter}`, text };
  });
}

export const EXTRA_ITEM_IDS = [
  'exp_all', 'rare_candy', 'trade_cable', 'fire_stone', 'water_stone', 'thunder_stone', 'leaf_stone',
  'moon_stone', 'sun_stone', 'shiny_stone', 'dusk_stone', 'dawn_stone', 'ice_stone',
] as const;

export function mapServerExtras(inventory: Record<string, number>): ExtrasInventory {
  const out = { battle_points: inventory.battle_points ?? 0 } as ExtrasInventory;
  for (const id of EXTRA_ITEM_IDS) out[id] = inventory[id] ?? 0;
  return out;
}

