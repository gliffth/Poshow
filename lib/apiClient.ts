export class ApiError extends Error {
  constructor(message: string, public status?: number) {
    super(message);
    this.name = 'ApiError';
  }
}

// free hosting sleeps when idle and the first request after that can take ~50s — so the default is
// generous, and the health check below is even more patient
const DEFAULT_TIMEOUT_MS = 30000;

export type RequestResult = { ok: true; ms: number } | { ok: false };
const resultListeners = new Set<(r: RequestResult) => void>();

/** Every request reports how long the server took, or that it never answered; the connection indicator listens. */
export function subscribeRequestResults(fn: (r: RequestResult) => void): () => void {
  resultListeners.add(fn);
  return () => { resultListeners.delete(fn); };
}

function report(r: RequestResult) {
  resultListeners.forEach((fn) => fn(r));
}

/** `quiet`: don't count a successful reply as a latency sample (a long poll is slow on purpose). */
async function request<T>(path: string, init?: RequestInit, timeoutMs = DEFAULT_TIMEOUT_MS, quiet = false): Promise<T> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);

  const token = getToken();
  const startedAt = Date.now();
  let res: Response;
  try {
    res = await fetch(`${API_BASE}${path}`, {
      ...init,
      signal: controller.signal,
      headers: {
        'Content-Type': 'application/json',
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
        ...(init?.headers ?? {}),
      },
    });
  } catch (err) {
    report({ ok: false });
    if (err instanceof DOMException && err.name === 'AbortError') {
      throw new ApiError('Request timed out — the server took too long to respond.');
    }
    throw new ApiError(err instanceof Error ? err.message : 'Network request failed.');
  } finally {
    clearTimeout(timeout);
  }
  if ([502, 503, 504].includes(res.status)) report({ ok: false });
  else if (!quiet) report({ ok: true, ms: Date.now() - startedAt });

  if (!res.ok) {
    let detail = res.statusText;
    try {
      const body = await res.json();
      detail = body.detail ?? detail;
    } catch {
      // response wasn't JSON — keep statusText
    }
    throw new ApiError(detail, res.status);
  }
  return res.json() as Promise<T>;
}

