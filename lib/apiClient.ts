// ── PvP ──
export interface PvpFormat {
  id: string; name: string; blurb: string; bring: number; pick: number; active: number;
  level_cap: number | null; species_clause: boolean; held_items: boolean; turn_timer: number; rated: boolean; queue: boolean;
}
export interface PvpCandidate {
  id: string; species: string; nickname: string; level: number; types: string[]; ability: string | null; moves: string[];
  hp: number; max_hp: number; held_item: string | null; dex_id: number | null; eligible: boolean; reasons: string[];
}
export interface PvpPreset { name: string; format_id: string; ids: string[]; stale?: boolean }
export interface PvpHistoryRow { ts: number; opp: string; format: string; won: boolean; delta: number; rated: boolean }
export interface PvpProfile {
  elo: number; wins: number; losses: number; ratings: Record<string, { elo: number; w: number; l: number }>;
  history: PvpHistoryRow[]; teams: PvpPreset[];
}
export interface PvpMon {
  species: string; nickname?: string; level: number; hp?: number; max_hp?: number; status?: string | null; dex_id?: number | null;
  moves?: { id: string; pp: number | null }[]; ability?: string | null; held_item?: string | null;
}
export interface PvpSide { name: string; active: number; chosen: boolean; picked: boolean; team: PvpMon[] }
export interface PvpFormatBrief { id: string; name: string; bring: number; pick: number; level_cap: number | null; turn_timer: number; rated: boolean }
export interface PvpMatch {
  id: string; status: 'pending' | 'queued' | 'active' | 'finished' | 'abandoned'; you: 'a' | 'b'; seq: number;
  format: PvpFormatBrief | null; names?: Record<string, string>;
  turn?: number; phase?: 'preview' | 'choose' | 'switch' | 'done'; winner?: 'a' | 'b' | null; log: string[];
  me?: PvpSide; foe?: PvpSide; deadline?: number | null; waiting?: boolean; needs_pick?: boolean; needs_switch?: boolean;
  elo?: Record<string, { name: string; now: number; delta: number }> | null;
}
export interface PvpInvite { id: string; from: string; to: string; format: { id: string; name: string; pick: number; bring: number; level_cap: number | null } | null }
export interface PvpSummary { incoming: PvpInvite[]; outgoing: PvpInvite[]; queue: PvpMatch | null; active: PvpMatch | null }
export type PvpPoll = PvpSummary | { unchanged: true; seq: number; deadline?: number | null };
export type PvpAction = { type: 'move'; move: string } | { type: 'switch'; to: number } | { type: 'pick'; order: number[] };

export const pvpFormats = () => request<{ formats: PvpFormat[]; friendly_limits: Record<string, [number, number]> }>('/api/pvp/formats');
export const pvpCollection = (uid: number, formatId: string, rules?: { level_cap?: number | null; pick?: number; held_items?: boolean }) =>
  request<{ format: PvpFormat; pokemon: PvpCandidate[] }>(`/api/pvp/collection?user_id=${uid}&format_id=${formatId}${rules?.level_cap ? `&level_cap=${rules.level_cap}` : ""}${rules?.pick ? `&pick=${rules.pick}` : ""}${rules?.held_items === false ? "&held_items=false" : ""}`);
export const pvpProfile = (uid: number) => request<PvpProfile>(`/api/pvp/profile?user_id=${uid}`);
export const pvpSaveTeam = (uid: number, name: string, formatId: string, ids: string[]) =>
  request<{ ok: boolean; teams: PvpPreset[] }>('/api/pvp/teams', { method: 'POST', body: JSON.stringify({ user_id: uid, name, format_id: formatId, ids }) });
export const pvpDeleteTeam = (uid: number, name: string) =>
  request<{ ok: boolean; teams: PvpPreset[] }>(`/api/pvp/teams?user_id=${uid}&name=${encodeURIComponent(name)}`, { method: 'DELETE' });
export const pvpQueueJoin = (uid: number, formatId: string, ids: string[]) =>
  request<{ matched: boolean; match?: PvpMatch; queue?: PvpMatch }>('/api/pvp/queue/join', { method: 'POST', body: JSON.stringify({ user_id: uid, format_id: formatId, ids }) });
export const pvpQueueLeave = (uid: number) =>
  request<{ left: number }>('/api/pvp/queue/leave', { method: 'POST', body: JSON.stringify({ user_id: uid }) });
export const pvpChallenge = (uid: number, username: string, ids: string[], rules: Record<string, unknown>) =>
  request<PvpMatch>('/api/pvp/challenge', { method: 'POST', body: JSON.stringify({ user_id: uid, username, format_id: 'friendly', ids, rules }) });
export const pvpRespond = (uid: number, matchId: string, accept: boolean, ids?: string[]) =>
  request<PvpMatch | { declined: true }>('/api/pvp/respond', { method: 'POST', body: JSON.stringify({ user_id: uid, match_id: matchId, accept, ids }) });
export const pvpState = (uid: number, since?: number) =>
  request<PvpPoll>(`/api/pvp/state?user_id=${uid}${since !== undefined ? `&since=${since}` : ''}`);
/** Long poll: the server answers when the match changes, or after about 20 s with { unchanged: true }. */
export const pvpWait = (uid: number, since: number, incoming: number) =>
  request<PvpPoll>(`/api/pvp/wait?user_id=${uid}&since=${since}&inc=${incoming}&timeout=20`, undefined, 35000, true);
export const pvpAction = (uid: number, matchId: string, action: PvpAction, turn: number | undefined, requestId: string) =>
  request<PvpMatch>('/api/pvp/action', { method: 'POST', body: JSON.stringify({ user_id: uid, match_id: matchId, action, turn, request_id: requestId }) });
export const pvpForfeit = (uid: number, matchId: string) =>
  request<PvpMatch>('/api/pvp/forfeit', { method: 'POST', body: JSON.stringify({ user_id: uid, match_id: matchId }) });
