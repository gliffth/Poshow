export interface HealthStatus {
  reachable: boolean;
  persistent: boolean;
}

export async function checkHealth(): Promise<HealthStatus> {
  try {
    const res = await request<{ ok: boolean; database: boolean }>('/api/health', undefined, 65000);
    return { reachable: !!res.ok, persistent: !!res.database };
  } catch {
    return { reachable: false, persistent: false };
  }
}

