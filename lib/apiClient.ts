export interface HeldResponse {
  message: string;
  pokemon: StorageMon;
  inventory: Record<string, number>;
}

/** Put a held item on a Pokémon (it swaps out whatever it held). Refused during a battle. */
export function heldEquip(userId: number, pokemonId: string, item: string) {
  return request<HeldResponse>('/api/held/equip', {
    method: 'POST', body: JSON.stringify({ user_id: userId, pokemon_id: pokemonId, item }),
  });
}

/** Take the held item back into the bag. Refused during a battle. */
export function heldUnequip(userId: number, pokemonId: string) {
  return request<HeldResponse>('/api/held/unequip', {
    method: 'POST', body: JSON.stringify({ user_id: userId, pokemon_id: pokemonId }),
  });
}

