// Starter choices per region — the server validates against the same list (api/index.py STARTERS).
// Every generation orders them grass / fire / water.

export type StarterType = 'grass' | 'fire' | 'water';

export interface StarterChoice {
  species: string;
  pokedexId: number;
  type: StarterType;
}

export interface RegionDef {
  id: string;
  name: string;
  gen: string;
  blurb: string;
  starters: StarterChoice[];
}

const trio = (g: [string, number], f: [string, number], w: [string, number]): StarterChoice[] => [
  { species: g[0], pokedexId: g[1], type: 'grass' },
  { species: f[0], pokedexId: f[1], type: 'fire' },
  { species: w[0], pokedexId: w[1], type: 'water' },
];

